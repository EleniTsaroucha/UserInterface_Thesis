# Ο μήνας της συνεδρίας. Σημειώνεται οπτικά στο διάγραμμα, ώστε το ερώτημα
# «σε ποια φάση βρισκόμαστε» να απαντάται από το ίδιο το συνημμένο και όχι
# από εξωτερική γνώση του συμμετέχοντα.
_CURRENT_MONTH_INDEX = 8          # Σεπτέμβριος

CRED_SUBJECT_TOKEN = "{CRED_SUBJECT}"


def _build_gantt_html(title: str, subtitle: str,
                       phases: list[tuple[str, int, int, str]]) -> str:
    n_months = len(_MONTHS_GR)
    header_cells = ""
    for i, month in enumerate(_MONTHS_GR):
        if i == _CURRENT_MONTH_INDEX:
            header_cells += (
                f'<th bgcolor="#fde293" style="padding:4px 6px; font-size:11px; '
                f'color:#101114;"><b>{month}</b></th>'
            )
        else:
            header_cells += (
                f'<th style="padding:4px 6px; font-size:11px; '
                f'color:#5f6368;">{month}</th>'
            )
    rows = []
    for name, start, end, color in phases:
        duration = end - start + 1
        remaining = n_months - end - 1
        cells = (f'<td style="padding:5px 10px; font-size:12px; '
                 f'white-space:nowrap; color:#101114;">{name}</td>')
        if start > 0:
            cells += f'<td colspan="{start}"></td>'
        cells += f'<td colspan="{duration}" bgcolor="{color}">&nbsp;</td>'
        if remaining > 0:
            cells += f'<td colspan="{remaining}"></td>'
        rows.append(f"<tr>{cells}</tr>")
    rows_html = "".join(rows)
    return (
        f"<div style=\"font-family:'Segoe UI'; color:#101114;\">"
        f"<h2 style=\"margin-bottom:2px;\">{title}</h2>"
        f"<p style=\"color:#5f6368; font-size:12px; margin-top:0;\">{subtitle}</p>"
        f"<table border=\"1\" cellspacing=\"0\" cellpadding=\"0\" "
        f"style=\"border-collapse:collapse; width:100%; border-color:#d7dbe0;\">"
        f"<tr><th style=\"padding:4px 10px; text-align:left; font-size:11px; "
        f"color:#5f6368;\">Φάση</th>{header_cells}</tr>"
        f"{rows_html}"
        f"</table>"
        f"<p style=\"color:#80868b; font-size:10.5px; margin-top:10px;\">"
        f"Ενημερώθηκε: Σεπτέμβριος 2026 &nbsp;·&nbsp; "
        f"Ο τρέχων μήνας σημειώνεται με κίτρινο.</p>"
        f"</div>"
    )


